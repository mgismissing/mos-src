        mov ax, (9 + 6) + (SCR13_WIDTH * (5 + (32 * 1)))
        mov bx, winico_console_16
        call scr13_draw_img_16x16

        ; DESKTOP APP "CONSOLE" TEXT
        mov ax, 9 + (SCR13_WIDTH * (5 + 16 + 2 + (32 * 1)))
        mov bx, winstr_console_icon_name
        mov dl, 0x0F
        call scr13_print_string

