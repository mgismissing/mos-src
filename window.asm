        jmp .start
    
    .desktop:
        cmp byte [win_current_selection], 0x01
        je .desktop_selection1
        cmp byte [win_current_selection], 0x02
        je .desktop_selection2
        cmp byte [win_current_selection], 0x03
        je .desktop_selection3
        cmp byte [win_current_selection], 0x04
        je .desktop_selection4
        cmp byte [win_current_selection], 0x05
        je .desktop_selection5
    .desktop_manager:
        call kb_waitForKey
        cmp ah, 0x1C                ; ENTER
        je .desktop_manager_enter
        cmp ah, 0x4B                ; LEFT
        je .desktop_manager_left
        cmp ah, 0x48                ; UP
        je .desktop_manager_left
        cmp ah, 0x50                ; DOWN
        je .desktop_manager_right
        cmp ah, 0x4D                ; RIGHT
        je .desktop_manager_right
        jmp .desktop_manager

    .desktop_manager_left:
        mov al, [win_min_selection]
        cmp byte [win_current_selection], al
        jle .desktop_manager
        dec byte [win_current_selection]
        jmp .start

    .desktop_manager_right:
        mov al, [win_max_selection]
        cmp byte [win_current_selection], al
        jge .desktop_manager
        inc byte [win_current_selection]
        jmp .start

    .desktop_manager_enter:
        mov byte al, [win_current_selection]
        mov byte [win_current_open_window], al
        jmp .start
    
    .desktop_selection1:
        m_win_draw_border 1, 3 + (32 * 0), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection2:
        m_win_draw_border 1, 3 + (32 * 1), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection3:
        m_win_draw_border 1, 3 + (32 * 2), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection4:
        m_win_draw_border 1, 3 + (32 * 3), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection5:
        m_win_draw_border 1, 3 + (32 * 4), 41, 30, 0x1B
        jmp .desktop_manager
    .loop:
        call kb_waitForKey
        cmp ah, 0x1C
        jne .loop
        ret

    jmp win_end

win_draw_background:
    ; BACKGROUND
    mov ax, 0x0000
    mov bx, SCR13_SIZE
    mov dl, 0x12 ; 0x7C: WINDOWS 95 BACKGROUND COLOR
    call scr13_draw_line

    ; LOGO
    mov ax, SCR13_HEIGHT_MIDDLE - (SCR13_WIDTH * 16) + SCR13_WIDTH_MIDDLE - (3 * 8)
    mov dl, 0x1E
    mov bx, 'M'
    call scr13_print_char_x4
    mov ax, SCR13_HEIGHT_MIDDLE - (SCR13_WIDTH * 16) + SCR13_WIDTH_MIDDLE - (1 * 8)
    mov dl, 0x19
    mov bx, .str_os
    call scr13_print_string_x4

    mov ax, SCR13_WIDTH * 191 + 1
    mov dl, 0x19
    mov bx, winstr_current_mode_16
    call scr13_print_string

    ret

    .str_os: db 'OS', 0

win_mouse_coords_to_index:
    mov ax, [winvar_mouse_y]
    mov dx, SCR13_WIDTH
    mul dx
    add ax, [winvar_mouse_x]
    mov [winvar_mouse_pos], ax

win_draw_window:                                ; win_draw_window(ax > Position, bx > Width, cx > Height) => None
    ; WINDOW - BASE SHAPE
    pusha
    mov dl, 0x1B
    call scr13_draw_rect
    popa

    ; WINDOW - TOP WHITE LINE
    pusha
    add ax, SCR13_WIDTH + 1
    add bx, ax
    sub bx, 3
    mov dl, 0x0F
    call scr13_draw_line
    popa

    pusha
    call win_mul_cx_times_width
    
    mov bx, ax
    add bx, cx
    inc ax
    sub bx, (SCR13_WIDTH * 2) - 1
    mov dl, 0x0F
    call scr13_draw_vertical_line
    popa

    ; WINDOW - TOP BRIGHTER LINE
    pusha
    add bx, ax
    dec bx
    mov dl, 0x1D
    call scr13_draw_line
    popa

    pusha
    call win_mul_cx_times_width
    
    mov bx, ax
    add bx, cx
    sub bx, SCR13_WIDTH
    mov dl, 0x1D
    call scr13_draw_vertical_line
    popa

    ; WINDOW - BOTTOM BLACK LINE
    pusha
    call win_mul_cx_times_width

    add ax, cx
    sub ax, SCR13_WIDTH
    add bx, ax
    mov dl, 0x11
    call scr13_draw_line
    popa

    pusha
    call win_mul_cx_times_width

    add ax, bx
    dec ax

    mov bx, ax
    add bx, cx
    mov dl, 0x11
    call scr13_draw_vertical_line
    popa

    ; WINDOW - BOTTOM DARK GRAY LINE
    pusha
    call win_mul_cx_times_width

    add ax, cx
    sub ax, (SCR13_WIDTH * 2) - 1 
    add bx, ax
    sub bx, 2
    mov dl, 0x17
    call scr13_draw_line
    popa

    pusha
    call win_mul_cx_times_width

    add ax, bx
    add ax, SCR13_WIDTH - 2

    mov bx, ax
    add bx, cx
    sub bx, (SCR13_WIDTH * 2)
    mov dl, 0x17
    call scr13_draw_vertical_line
    popa

    ; WINDOW TITLE BAR
    pusha
    add ax, (SCR13_WIDTH * 3) + 3
    sub bx, 6
    mov cx, 10
    mov dl, 0x01
    call scr13_draw_rect
    popa

    ; WINDOW TITLE
    pusha
    add ax, (SCR13_WIDTH * 4) + 5
    mov bx, [win_draw_window_title_str_pt]
    mov dl, 0x1F
    call scr13_print_string
    popa

    ; RETURN
    ret

win_mul_cx_times_width:
    push ax
    mov ax, cx
    mov cx, SCR13_WIDTH
    mul cx
    mov cx, ax
    pop ax
    ret

