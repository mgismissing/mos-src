bool gd_is_player_touching_ground(uint16_t plr_y) {
    return (plr_y >= 168) || (m13_get_pixel_color(m13_coords_to_index(48, plr_y + 8)) != 0x36);
}

bool gd_is_player_touching_wall(uint16_t plr_y) {
    return (m13_get_pixel_color(m13_coords_to_index(49, plr_y + 7)) != 0x36);
}

uint8_t gd_main() {
    uint16_t lvl_x = 0;
    uint16_t plr_y = 168;
    uint16_t plr_velocity_y = 10;
    uint16_t plr_gravity = plr_velocity_y;
    uint32_t old_ticks = 0;
    uint32_t game_ticks = 0;
    while (true) {
        // store current ticks
        old_ticks = timer_get_current_ticks();

        // clear screen
        m13_draw_rect(0, 320, 176, 0x36, 0x36);
        m13_draw_rect(m13_coords_to_index(0, 176), 320, 24, 0x01, 0x01);

        // draw map
        for (uint16_t y = 0; y < 8; y++) {
            for (uint16_t x = 0; x < 32; x++) {
                if (((x * 16 + 384 - lvl_x) >= 0) && ((x * 16 + 384 - lvl_x) <= 304)) {
                    if (level[y * 32 + x] == 1) {
                        m13_draw_img(m13_coords_to_index(x * 16 + 384 - lvl_x, y * 16 + 48), 16, 16, img_tile_block, 1);
                    }
                    if (level[y * 32 + x] == 2) {
                        m13_draw_img(m13_coords_to_index(x * 16 + 384 - lvl_x, y * 16 + 48), 16, 16, img_tile_spike, 1);
                    }
                    if (level[y * 32 + x] == 255) {
                        m13_draw_img(m13_coords_to_index(x * 16 + 384 - lvl_x, y * 16 + 48), 16, 16, img_tile_end, 1);
                    }
                }
            }
        }

        // draw player
        m13_draw_img(m13_coords_to_index(32, plr_y - 8), 16, 16, img_player, 1);

        // game logic
        game_ticks += timer_get_current_ticks() - old_ticks;

        if (kb_is_scancode_pressed(0x39) && gd_is_player_touching_ground(plr_y)) {
            plr_velocity_y = 18;
        }

        while (game_ticks >= 18) {
            lvl_x += 4;
            plr_y -= (plr_velocity_y - plr_gravity);
            if (plr_velocity_y > 0) {
                plr_velocity_y--;
            }
            while (gd_is_player_touching_ground(plr_y)) {
                if (plr_velocity_y < plr_gravity) {
                    plr_velocity_y = plr_gravity;
                }
                plr_y--;
            }
            plr_y++;
            game_ticks -= 18;
        }

        if (gd_is_player_touching_wall(plr_y)) {
            return m13_get_pixel_color(m13_coords_to_index(49, plr_y + 7)) != 0x0A;
        }
    }
}