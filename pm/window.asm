pm_win_are_mouse_coords_on_area:                   ; pm_win_are_mouse_coords_on_area(ax > Top Left Corner X, bx > Top Left Corner Y, cx > Bottom Right Corner X, dx > Bottom Right Corner Y) => cf > Mouse Pointer is on area
    cmp [pm_winvar_mouse_x], ax
    jl .outside
    cmp [pm_winvar_mouse_x], cx
    jg .outside

    cmp [pm_winvar_mouse_y], bx
    jl .outside
    cmp [pm_winvar_mouse_y], dx
    jg .outside

    stc
    ret

    .outside:
    clc
    ret

