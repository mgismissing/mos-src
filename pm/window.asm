pm_win_start:
    mov byte [pm_win_current_open_window], 0x03
    mov byte [pm_win_current_selection], 0x03
    jmp pm_win_main

pm_win_main:
    .start:
        ; DESKTOP BACKGROUND
        call pm_win_draw_background

        ; DESKTOP APP "SHUTDOWN" ICON
        mov eax, (9 + 6) + (SCR13_WIDTH * (5 + (32 * 0)))
        mov ebx, pm_winico_turn_off_computer_full_16
        call pm_scr13_draw_img_16x16

        ; DESKTOP APP "SHUTDOWN" TEXT
        mov ax, 7 + (SCR13_WIDTH * (5 + 16 + 2 + (32 * 0)))
        mov bx, pm_winstr_shutdown_icon_name
        mov dl, 0x0F
        call pm_scr13_print_string

        ; DESKTOP APP "CONSOLE" ICON
        mov ax, (9 + 6) + (SCR13_WIDTH * (5 + (32 * 1)))
        mov bx, pm_winico_console_16
        call pm_scr13_draw_img_16x16

        ; DESKTOP APP "CONSOLE" TEXT
        mov ax, 9 + (SCR13_WIDTH * (5 + 16 + 2 + (32 * 1)))
        mov bx, pm_winstr_console_icon_name
        mov dl, 0x0F
        call pm_scr13_print_string

        ; DESKTOP APP "WELCOME" ICON
        mov ax, (9 + 6) + (SCR13_WIDTH * (5 + (32 * 2)))
        mov bx, pm_winico_disc_drive_16
        call pm_scr13_draw_img_16x16

        ; DESKTOP APP "WELCOME" TEXT
        mov ax, 9 + (SCR13_WIDTH * (5 + 16 + 2 + (32 * 2)))
        mov bx, pm_winstr_welcome_icon_name
        mov dl, 0x0F
        call pm_scr13_print_string

        ; DESKTOP APP "64-BIT MODE" ICON
        mov ax, (9 + 6) + (SCR13_WIDTH * (5 + (32 * 3)))
        mov bx, pm_winico_chip_16
        call pm_scr13_draw_img_16x16

        ; DESKTOP APP "64-BIT MODE" TEXT
        mov ax, 11 + (SCR13_WIDTH * (5 + 16 + 2 + (32 * 3)))
        mov bx, pm_winstr_64_bit_mode_icon_name
        mov dl, 0x0F
        call pm_scr13_print_string

        ; DESKTOP APP "CREDITS" ICON
        mov ax, (9 + 6) + (SCR13_WIDTH * (5 + (32 * 4)))
        mov bx, pm_winico_constructor_16
        call pm_scr13_draw_img_16x16

        ; DESKTOP APP "CREDITS" TEXT
        mov ax, 9 + (SCR13_WIDTH * (5 + 16 + 2 + (32 * 4)))
        mov bx, pm_winstr_credits_icon_name
        mov dl, 0x0F
        call pm_scr13_print_string

        ; CURRENT WINDOW SHOWER
        cmp byte [pm_win_current_open_window], 0x01
        je cmd_run_shutdown
        cmp byte [pm_win_current_open_window], 0x02
        je cmd_start
        cmp byte [pm_win_current_open_window], 0x03
        je .window_welcome
        cmp byte [pm_win_current_open_window], 0x04
        je pm_enter
        cmp byte [pm_win_current_open_window], 0x05
        je .window_credits
        jmp .window_welcome
    .window_welcome:
        ; WINDOW
        m_pm_win_draw_window 60, 20, 200, 160, pm_winstr_welcome_window_title

        ; WINDOW IMAGE BACKGROUND BORDER
        mov dl, 0x00
        mov ax, 65 + (SCR13_WIDTH * 36)
        mov bx, (65 + 42) + (SCR13_WIDTH * 36)
        call pm_scr13_draw_line
        mov ax, 65 + (SCR13_WIDTH * 36)
        mov bx, 65 + (SCR13_WIDTH * (36 + 139))
        call pm_scr13_draw_vertical_line
        mov ax, 65 + (SCR13_WIDTH * (36 + 138))
        mov bx, (65 + 42) + (SCR13_WIDTH * (36 + 138))
        call pm_scr13_draw_line
        mov ax, (65 + 41) + (SCR13_WIDTH * 36)
        mov bx, (65 + 41) + (SCR13_WIDTH * (36 + 139))
        call pm_scr13_draw_vertical_line

        ; WINDOW IMAGE BACKGROUND
        mov eax, 66 + (SCR13_WIDTH * 37)
        mov ebx, 40
        mov ecx, 137
        mov dl, 0x94
        call pm_scr13_draw_rect

        ; WINDOW IMAGE
        mov eax, 70 + (SCR13_WIDTH * 40)
        mov ebx, pm_winico_disc_drive_32
        call pm_scr13_draw_img_32x32

        ; WINDOW TEXT
        mov dl, 0x00
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 0)))
        mov bx, pm_winstr_welcome_window_desc1
        call pm_scr13_print_string
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 1)))
        mov bx, pm_winstr_welcome_window_desc2
        call pm_scr13_print_string
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 2)))
        mov bx, pm_winstr_welcome_window_desc3
        call pm_scr13_print_string
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 4)))
        mov bx, pm_winstr_welcome_window_desc4
        call pm_scr13_print_string
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 5)))
        mov bx, pm_winstr_welcome_window_desc5
        call pm_scr13_print_string
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 6)))
        mov bx, pm_winstr_welcome_window_desc6
        call pm_scr13_print_string
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 7)))
        mov bx, pm_winstr_welcome_window_desc7
        call pm_scr13_print_string

        jmp .window_welcome_loop

    .window_welcome_loop:
        ; WINDOW BUTTONS
        m_pm_win_draw_button 198, 156, 54, 16, pm_winstr_button_ok
        m_pm_win_draw_dotted_border 201, 159, 47, 9, 0x00

        ; BUTTON CHECKER
        call .loop
        m_pm_win_draw_pressed_button 198, 156, 54, 16, pm_winstr_button_ok
        m_pm_win_draw_dotted_border 201, 159, 47, 9, 0x00
        jmp $
        mov byte [pm_win_current_open_window], 0x00
        jmp .start
    .window_credits:
        ; WINDOW
        m_pm_win_draw_window 60, 20, 200, 160, pm_winstr_credits_title

        ; WINDOW IMAGE
        mov ax, 70 + (SCR13_WIDTH * 40)
        mov bx, pm_winico_constructor_32
        call pm_scr13_draw_img_32x32

        ; WINDOW TEXT
        mov dl, 0x00
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 0)))
        mov bx, pm_winstr_credits_desc1
        call pm_scr13_print_string
        mov dl, 0x13
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 1)))
        mov bx, pm_winstr_credits_desc2
        call pm_scr13_print_string
        mov dl, 0x00
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 3)))
        mov bx, pm_winstr_credits_desc3
        call pm_scr13_print_string
        mov dl, 0x13
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 4)))
        mov bx, pm_winstr_credits_desc4
        call pm_scr13_print_string
        mov dl, 0x00
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 6)))
        mov bx, pm_winstr_credits_desc5
        call pm_scr13_print_string
        mov dl, 0x13
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 7)))
        mov bx, pm_winstr_credits_desc6
        call pm_scr13_print_string
        mov dl, 0x13
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 8)))
        mov bx, pm_winstr_credits_desc7
        call pm_scr13_print_string
        mov dl, 0x13
        mov ax, 110 + (SCR13_WIDTH * (36 + (8 * 9)))
        mov bx, pm_winstr_credits_desc8
        call pm_scr13_print_string

        jmp .window_credits_loop

    .window_credits_loop:
        ; WINDOW BUTTONS
        m_pm_win_draw_button 198, 156, 54, 16, pm_winstr_button_ok
        m_pm_win_draw_dotted_border 201, 159, 47, 9, 0x00

        ; BUTTON CHECKER
        call .loop
        m_pm_win_draw_pressed_button 198, 156, 54, 16, pm_winstr_button_ok
        m_pm_win_draw_dotted_border 201, 159, 47, 9, 0x00
        call delay_50ms
        mov byte [pm_win_current_open_window], 0x00
        jmp .start
    
    .desktop:
        cmp byte [pm_win_current_selection], 0x01
        je .desktop_selection1
        cmp byte [pm_win_current_selection], 0x02
        je .desktop_selection2
        cmp byte [pm_win_current_selection], 0x03
        je .desktop_selection3
        cmp byte [pm_win_current_selection], 0x04
        je .desktop_selection4
        cmp byte [pm_win_current_selection], 0x05
        je .desktop_selection5
    .desktop_manager:
        call pm_kb_waitForKey
        cmp ah, 0x1C                ; ENTER
        je .desktop_manager_enter
        cmp ah, 0x4B                ; LEFT
        je .desktop_manager_left
        cmp ah, 0x48                ; UP
        je .desktop_manager_left
        cmp ah, 0x50                ; DOWN
        je .desktop_manager_right
        cmp ah, 0x4D                ; RIGHT
        je .desktop_manager_right
        jmp .desktop_manager

    .desktop_manager_left:
        mov al, [pm_win_min_selection]
        cmp byte [pm_win_current_selection], al
        jle .desktop_manager
        dec byte [pm_win_current_selection]
        jmp .start

    .desktop_manager_right:
        mov al, [pm_win_max_selection]
        cmp byte [pm_win_current_selection], al
        jge .desktop_manager
        inc byte [pm_win_current_selection]
        jmp .start

    .desktop_manager_enter:
        mov byte al, [pm_win_current_selection]
        mov byte [pm_win_current_open_window], al
        jmp .start
    
    .desktop_selection1:
        m_pm_win_draw_border 1, 3 + (32 * 0), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection2:
        m_pm_win_draw_border 1, 3 + (32 * 1), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection3:
        m_pm_win_draw_border 1, 3 + (32 * 2), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection4:
        m_pm_win_draw_border 1, 3 + (32 * 3), 41, 30, 0x1B
        jmp .desktop_manager
    .desktop_selection5:
        m_pm_win_draw_border 1, 3 + (32 * 4), 41, 30, 0x1B
        jmp .desktop_manager
    .loop:
        call pm_kb_waitForKey
        cmp ah, 0x1C
        jne .loop
        ret

    jmp pm_win_end

pm_win_draw_background:
    ; BACKGROUND
    mov ax, 0x0000
    mov bx, SCR13_SIZE
    mov dl, 0x12 ; 0x7C: WINDOWS 95 BACKGROUND COLOR
    call pm_scr13_draw_line

    ; LOGO
    mov ax, SCR13_HEIGHT_MIDDLE - (SCR13_WIDTH * 16) + SCR13_WIDTH_MIDDLE - (3 * 8)
    mov dl, 0x1E
    mov bx, 'M'
    call pm_scr13_print_char_x4
    mov ax, SCR13_HEIGHT_MIDDLE - (SCR13_WIDTH * 16) + SCR13_WIDTH_MIDDLE - (1 * 8)
    mov dl, 0x19
    mov bx, .str_os
    call pm_scr13_print_string_x4

    mov ax, SCR13_WIDTH * 191 + 1
    mov dl, 0x19
    mov bx, pm_winstr_current_mode_16
    call pm_scr13_print_string

    ret

    .str_os: db 'OS', 0

pm_win_mouse_coords_to_index:
    mov ax, [pm_winvar_mouse_y]
    mov dx, SCR13_WIDTH
    mul dx
    add ax, [pm_winvar_mouse_x]
    mov [pm_winvar_mouse_pos], ax

pm_win_draw_window:                                ; pm_win_draw_window(ax > Position, bx > Width, cx > Height) => None
    ; WINDOW - BASE SHAPE
    pusha
    mov dl, 0x1B
    call pm_scr13_draw_rect
    popa

    ; WINDOW - TOP WHITE LINE
    pusha
    add ax, SCR13_WIDTH + 1
    add bx, ax
    sub bx, 3
    mov dl, 0x0F
    call pm_scr13_draw_line
    popa

    pusha
    call pm_win_mul_cx_times_width
    
    mov bx, ax
    add bx, cx
    inc ax
    sub bx, (SCR13_WIDTH * 2) - 1
    mov dl, 0x0F
    call pm_scr13_draw_vertical_line
    popa

    ; WINDOW - TOP BRIGHTER LINE
    pusha
    add bx, ax
    dec bx
    mov dl, 0x1D
    call pm_scr13_draw_line
    popa

    pusha
    call pm_win_mul_cx_times_width
    
    mov bx, ax
    add bx, cx
    sub bx, SCR13_WIDTH
    mov dl, 0x1D
    call pm_scr13_draw_vertical_line
    popa

    ; WINDOW - BOTTOM BLACK LINE
    pusha
    call pm_win_mul_cx_times_width

    add ax, cx
    sub ax, SCR13_WIDTH
    add bx, ax
    mov dl, 0x11
    call pm_scr13_draw_line
    popa

    pusha
    call pm_win_mul_cx_times_width

    add ax, bx
    dec ax

    mov bx, ax
    add bx, cx
    mov dl, 0x11
    call pm_scr13_draw_vertical_line
    popa

    ; WINDOW - BOTTOM DARK GRAY LINE
    pusha
    call pm_win_mul_cx_times_width

    add ax, cx
    sub ax, (SCR13_WIDTH * 2) - 1 
    add bx, ax
    sub bx, 2
    mov dl, 0x17
    call pm_scr13_draw_line
    popa

    pusha
    call pm_win_mul_cx_times_width

    add ax, bx
    add ax, SCR13_WIDTH - 2

    mov bx, ax
    add bx, cx
    sub bx, (SCR13_WIDTH * 2)
    mov dl, 0x17
    call pm_scr13_draw_vertical_line
    popa

    ; WINDOW TITLE BAR
    pusha
    add ax, (SCR13_WIDTH * 3) + 3
    sub bx, 6
    mov cx, 10
    mov dl, 0x01
    call pm_scr13_draw_rect
    popa

    ; WINDOW TITLE
    pusha
    add eax, (SCR13_WIDTH * 4) + 5
    mov ebx, [pm_win_draw_window_title_str_pt]
    mov dl, 0x1F
    call pm_scr13_print_string
    popa

    ; RETURN
    ret

pm_win_mul_cx_times_width:
    push ax
    mov ax, cx
    mov cx, SCR13_WIDTH
    mul cx
    mov cx, ax
    pop ax
    ret

